vim.opt.runtimepath:prepend(vim.fn.getcwd())
local runtime = require('hellshake_yano')
local core = require('hellshake_yano.core')
local function eq(a,b) assert(vim.deep_equal(a,b),vim.inspect({expected=a,actual=b})) end
vim.api.nvim_buf_set_lines(0,0,-1,false,{'alpha beta gamma'})
vim.api.nvim_win_set_cursor(0,{1,0})
runtime.setup({singleCharKeys='AS',motionTimeout=100})
vim.api.nvim_feedkeys('A','t',false)
eq('jumped',runtime.show())
eq({1,6},vim.api.nvim_win_get_cursor(0))
eq(false,core.get_state().visible)
vim.api.nvim_win_set_cursor(0,{1,0})
vim.api.nvim_feedkeys('z','t',false)
eq('cancelled',runtime.show())
eq(string.byte('z'),vim.fn.getchar(0))
local start=vim.uv.hrtime()
eq('timeout',runtime.show())
assert((vim.uv.hrtime()-start)/1e6 < 500,'input timeout must be bounded')
eq(false,core.get_state().visible)

-- Re-entrant cancellation while waiting must not jump in a newer session.
vim.defer_fn(function() runtime.disable() end,5)
eq('cancelled',runtime.show())
eq(false,core.get_config().enabled)
runtime.enable()
vim.api.nvim_feedkeys(vim.api.nvim_replace_termcodes('<Esc>',true,false,true),'t',false)
eq('cancelled',runtime.show())

-- Continuous mode stops at the configured bound, with no recursive stack growth.
runtime.setup({continuousHintMode=true,maxContinuousJumps=2,singleCharKeys='A',motionTimeout=100})
vim.api.nvim_win_set_cursor(0,{1,0})
vim.api.nvim_feedkeys('AA','t',false)
eq('jumped',runtime.show())
eq({1,11},vim.api.nvim_win_get_cursor(0))
eq(false,core.get_state().visible)

-- Explicit activation is idempotent and does not overwrite an unrelated map.
vim.keymap.set('n','w',':echo "user-map"<CR>',{desc='user map'})
runtime.setup({countedMotions={'w','j'},triggerOnHjkl=false,perKeyMotionCount={j=2}})
runtime.activate()
eq('user map',vim.fn.maparg('w','n',false,true).desc)
assert(vim.fn.exists(':HellshakeYanoToggle') == 2)
runtime.activate()
vim.cmd('HellshakeYanoSetHighlight Search IncSearch')
eq('Search',runtime.get_config().highlightHintMarker)
vim.cmd('HellshakeYanoSetCount 4')
eq(4,runtime.get_config().defaultMotionCount)
vim.cmd('HellshakeYanoSetTimeout 150')
eq(150,runtime.get_config().motionTimeout)
vim.cmd('HellshakeYanoSetCountedMotions j k')
assert(vim.fn.maparg('k','n')~='')
assert(vim.fn.maparg('j','n',false,true).desc:find('hellshake%-yano'))
runtime.update_config({multiWindowMode=true,singleCharKeys='A'})
vim.api.nvim_win_set_cursor(0,{1,0})
vim.api.nvim_feedkeys('A','t',false)
eq('jumped',runtime.show())
eq(false,core.get_state().visible)
runtime.deactivate()
eq('user map',vim.fn.maparg('w','n',false,true).desc)
eq('',vim.fn.maparg('j','n'))
eq(0,vim.fn.exists(':HellshakeYanoToggle'))
assert(vim.v.errmsg == '', vim.v.errmsg)
print('PASS: native input loop, timeout, cancellation, activation ownership')
assert(vim.v.errmsg == '', vim.v.errmsg)
vim.cmd('qa!')
