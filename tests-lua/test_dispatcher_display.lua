vim.opt.runtimepath:prepend(vim.fn.getcwd())
vim.o.hidden=true
local runtime=require('hellshake_yano')
local dispatcher=require('hellshake_yano.dispatcher')
local core=require('hellshake_yano.core')
local function eq(a,b) assert(vim.deep_equal(a,b),vim.inspect({expected=a,actual=b})) end
runtime.setup({singleCharKeys='/',multiCharKeys='BC'})
vim.api.nvim_buf_set_lines(0,0,-1,false,{'日本語 alpha beta'})
local id=dispatcher.request('displayShowHint',{1,11,'A'})
assert(id>0)
local marks=vim.api.nvim_buf_get_extmarks(0,core.namespace,0,-1,{details=true})
eq(10,marks[1][3])
eq('A',marks[1][4].virt_text[1][1])
eq(-1,dispatcher.request('displayShowHint',{'bad',1,'A'}))
dispatcher.request('displayHideAll',{})
eq(0,#vim.api.nvim_buf_get_extmarks(0,core.namespace,0,-1,{}))
local raw=dispatcher.request('detectWords',{999999})
eq(11,raw[1].byteCol)
eq(8,raw[1].col)
local buffer=vim.api.nvim_get_current_buf()
vim.cmd('vnew')
vim.api.nvim_buf_set_lines(0,0,-1,false,{'gamma delta'})
local other=vim.api.nvim_get_current_win()
assert(dispatcher.request('displayShowHintWithWindow',{other,1,7,'B'})>0)
dispatcher.request('displayHideAll',{})
eq(0,#vim.api.nvim_buf_get_extmarks(0,core.namespace,0,-1,{}))
eq(0,#vim.api.nvim_buf_get_extmarks(buffer,core.namespace,0,-1,{}))
local multi=dispatcher.request('showHintsMultiWindow',{})
assert(#multi>1 and multi[1].word.winid==other)
assert(not runtime.get_config().multiWindowMode,'display-only multi-window call mutated configuration')
assert(multi[1].hintByteCol>0)
dispatcher.request('hideHintsMultiWindow',{})
-- Hint floats are pooled and hidden, so count only windows still shown.
eq(2,#vim.tbl_filter(function(w) return not vim.api.nvim_win_get_config(w).hide end,vim.api.nvim_list_wins()))
vim.cmd('only')
vim.api.nvim_win_set_cursor(0,{1,0})
core.show({{text='delta',line=1,col=7},{text='gamma',line=1,col=1}})
eq(1,dispatcher.request('displayGetPopupCount',{}))
dispatcher.request('highlightCandidateHints',{'/'})
eq('/',core.get_state().prefix)
eq({1,0},vim.api.nvim_win_get_cursor(0)) -- Highlighting must never jump.
dispatcher.request('showHints',{})
eq(1,#core.get_state().targets)
dispatcher.request('displayHideAll',{})
eq('HellshakeYanoMarker',dispatcher.request('getHighlightGroup',{'hint'}))
assert(vim.v.errmsg=='',vim.v.errmsg)
print('PASS: legacy display dispatcher byte positions, cleanup and highlight without selection')
vim.cmd('qa!')
