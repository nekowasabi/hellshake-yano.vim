vim.opt.runtimepath:prepend(vim.fn.getcwd())
local motion = require('hellshake_yano.motion')
local config = require('hellshake_yano.config')
local cfg = config.resolve({perKeyMotionCount={j=2}, suppressOnKeyRepeat=false})
assert(not motion.record(1, 'j', 1, cfg, 100))
assert(motion.record(1, 'j', 1, cfg, 200))
assert(not motion.record(1, 'j', 1, cfg, 300))
assert(not motion.record(1, 'w', 1, cfg, 400))
assert(not motion.record(2, 'w', 1, cfg, 500))
assert(not motion.record(1, 'w', 2, cfg, 600))
assert(not motion.record(1, 'w', 1, cfg, 700))
assert(not motion.record(1, 'w', 1, cfg, 800))
assert(motion.record(1, 'w', 1, cfg, 900))
motion.reset()
assert(not motion.record(1, 'j', 1, cfg, 100))
assert(not motion.record(1, 'j', 1, cfg, 3000))
cfg = config.resolve({perKeyMotionCount={j=2}})
motion.reset()
assert(not motion.record(1, 'j', 1, cfg, 100))
assert(not motion.record(1, 'j', 1, cfg, 110))
assert(not motion.record(1, 'j', 1, cfg, 200))
assert(motion.record(1, 'j', 1, cfg, 600))
cfg.enabled = false
assert(not motion.record(1, 'j', 1, cfg, 700))
assert(not motion.record(1, 'j', 1, cfg, 800))
print('PASS: native per-buffer/per-key motion counters, counts, timeout, repeat suppression')
assert(vim.v.errmsg == '', vim.v.errmsg)
vim.cmd('qa!')
