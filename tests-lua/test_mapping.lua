vim.opt.runtimepath:prepend(vim.fn.getcwd())
local runtime = require('hellshake_yano')
vim.api.nvim_buf_set_lines(0,0,-1,false,{'alpha beta','second line','third target','fourth target'})
vim.api.nvim_win_set_cursor(0,{1,0})
runtime.setup({countedMotions={'j'},triggerOnHjkl=false,perKeyMotionCount={j=2},
  suppressOnKeyRepeat=false,singleCharKeys='AS',motionTimeout=100})
runtime.activate()
vim.api.nvim_feedkeys('jjA','xt',false)
assert(vim.deep_equal({3,6},vim.api.nvim_win_get_cursor(0)),vim.inspect(vim.api.nvim_win_get_cursor(0)))
assert(vim.api.nvim_get_mode().mode=='n','hint input must not execute normal A')
-- Explicit counts execute the original motion and do not enter hint input.
vim.api.nvim_win_set_cursor(0,{1,0})
vim.api.nvim_feedkeys('2j','xt',false)
assert(vim.deep_equal({3,0},vim.api.nvim_win_get_cursor(0)))
vim.api.nvim_win_set_cursor(0,{1,0})
vim.api.nvim_feedkeys('vjjA','xt',false)
assert(vim.api.nvim_get_mode().mode=='v','visual selection must remain active')
assert(vim.deep_equal({3,6},vim.api.nvim_win_get_cursor(0)))
assert(vim.fn.line('v')==1 and vim.fn.col('v')==1,'visual anchor changed')
vim.api.nvim_feedkeys(vim.api.nvim_replace_termcodes('<Esc>',true,false,true),'xt',false)
runtime.deactivate()
-- A user's plain noremap (j -> gj) is wrapped, not skipped, and restored on deactivate.
vim.keymap.set('n','j','gj')
runtime.activate()
assert(vim.fn.maparg('j','n',false,true).callback,'existing noremap must be wrapped')
vim.api.nvim_win_set_cursor(0,{1,0})
vim.api.nvim_feedkeys('jjA','xt',false)
assert(vim.deep_equal({3,6},vim.api.nvim_win_get_cursor(0)),vim.inspect(vim.api.nvim_win_get_cursor(0)))
assert(vim.fn.maparg('j','n',false,true).callback()=='gj','wrapped mapping must keep the user rhs')
runtime.deactivate()
assert(vim.fn.maparg('j','n')=='gj','user mapping must be restored')
print('PASS: mapped motions finish before hint input; queued keys and counts retain semantics')
assert(vim.v.errmsg == '', vim.v.errmsg)
vim.cmd('qa!')
