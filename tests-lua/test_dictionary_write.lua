vim.opt.runtimepath:prepend(vim.fn.getcwd())
local dictionary=require('hellshake_yano.dictionary')
local runtime=require('hellshake_yano')
local dispatcher=require('hellshake_yano.dispatcher')
local function eq(a,b) assert(vim.deep_equal(a,b),vim.inspect({expected=a,actual=b})) end
local dir=vim.fn.tempname()
vim.fn.mkdir(dir,'p')
local path=dir..'/dictionary % # | safe.json'
vim.fn.writefile({'{"customWords":["old"],"preserveWords":["keep"],"metadata":{"mine":true},"unrelated":[1,2]}'},path)
runtime.setup({dictionaryPath=path})
dispatcher.request('addToDictionary',{' newword ','meaning','noun'})
local raw=vim.json.decode(table.concat(vim.fn.readfile(path),'\n'))
eq({'old','newword'},raw.customWords)
eq({1,2},raw.unrelated)
assert(raw.metadata.mine)
eq('meaning',raw.words[1].meaning)
assert(dispatcher.request('isInDictionary',{'keep'}),'preserveWords must be checked too')
assert(dispatcher.request('isInDictionary',{'newword'}))
dispatcher.request('addToDictionary',{'newword','changed'})
raw=vim.json.decode(table.concat(vim.fn.readfile(path),'\n'))
eq(2,#raw.customWords); eq(1,#raw.words); eq('changed',raw.words[1].meaning)
local yaml=dir..'/dictionary.yaml'
vim.fn.writefile({'# must survive unchanged','customWords: [old]'},yaml)
local before=vim.fn.readfile(yaml)
assert(not pcall(dictionary.add,yaml,'newword'))
eq(before,vim.fn.readfile(yaml))
local invalid=dir..'/broken.json'
vim.fn.writefile({'{broken'},invalid)
assert(not pcall(dictionary.add,invalid,'newword'))
eq({'{broken'},vim.fn.readfile(invalid))
assert(not pcall(dictionary.add,path,'   '))
-- A concurrent edit must win over the prepared replacement; no temp file may leak.
local original_write=vim.uv.fs_write
vim.uv.fs_write=function(...)
  local written=original_write(...)
  vim.fn.writefile({'{"customWords":["concurrent"]}'},path)
  return written
end
local succeeded=pcall(dictionary.add,path,'must-not-overwrite')
vim.uv.fs_write=original_write
assert(not succeeded)
eq({'concurrent'},dictionary.load(path).customWords)
eq({},vim.fn.glob(path..'.hellshake-yano-*',false,true))
local created=dir..'/newdir/new.json'
dictionary.add(created,'created')
eq({'created'},dictionary.load(created).customWords)
local prior=vim.api.nvim_get_current_win()
dispatcher.request('showDictionary',{})
local scratch=vim.api.nvim_get_current_buf()
eq('nofile',vim.bo[scratch].buftype)
assert(not vim.bo[scratch].modifiable)
assert(table.concat(vim.api.nvim_buf_get_lines(scratch,0,-1,false),'\n'):find('newword',1,true))
vim.api.nvim_win_close(0,true)
assert(not vim.api.nvim_buf_is_valid(scratch))
eq(prior,vim.api.nvim_get_current_win())
-- No Ex interpolation: spaces and semicolons belong to the literal filename.
dispatcher.request('editDictionary',{})
eq(path,vim.api.nvim_buf_get_name(0))
vim.api.nvim_buf_set_lines(0,0,-1,false,{'unsaved'})
vim.o.hidden=false
local other=dir..'/other.json'; vim.fn.writefile({'{}'},other)
runtime.setup({dictionaryPath=other})
assert(not pcall(dispatcher.request,'editDictionary',{}),'editing must not discard an unsaved buffer')
eq(path,vim.api.nvim_buf_get_name(0))
vim.api.nvim_buf_set_option(0,'modified',false)
vim.fn.delete(dir,'rf')
assert(vim.v.errmsg=='',vim.v.errmsg)
print('PASS: JSON dictionary add/update, preserved fields, rejected YAML/corruption and safe editor paths')
vim.cmd('qa!')
